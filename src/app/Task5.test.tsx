it('recovers from a committed archive when refreshing the archive list fails, without a duplicate archive', async () => {
  const { repo } = await setup(finished())
  const archive = await screen.findByRole('button', { name: 'Speichern und Beenden' })
  const listArchives = repo.listArchives.bind(repo)
  vi.spyOn(repo, 'listArchives').mockImplementation(listArchives).mockRejectedValueOnce(new Error('Archivliste nicht geladen'))
  const dispatch = vi.spyOn(repo, 'dispatch')
  fireEvent.click(archive)
  expect(await screen.findByRole('alert')).toHaveTextContent('Archivliste nicht geladen')
  expect(await repo.loadActive()).toBeUndefined()
  const committed = (await listArchives())[0]!
  expect(committed.status).toBe('archived')
  expect(screen.getByRole('heading', { name: 'Siegerehrung' })).toBeInTheDocument()
  const retry = screen.getByRole('button', { name: 'Speichern und Beenden' })
  await waitFor(() => expect(retry).toBeEnabled())
  fireEvent.click(retry)
  await screen.findByRole('heading', { name: 'Neue Meisterschaft' })
  const calls = dispatch.mock.calls.filter(c => c[3].type === 'archive')
  expect(calls).toHaveLength(2)
  expect(calls[0]![2]).toBe(calls[1]![2])
  expect(await listArchives()).toEqual([committed])
  expect(screen.getByRole('button', { name: /Eure bisherigen Meisterschaften/ })).toHaveTextContent('(1)')
  fireEvent.click(screen.getByRole('button', { name: 'Archiv' }))
  fireEvent.click(await screen.findByRole('button', { name: /Meisterschaft ansehen/ }))
  await screen.findByRole('heading', { name: 'Meisterschaft im Archiv' })
  expect(screen.queryByRole('button', { name: 'Speichern und Beenden' })).not.toBeInTheDocument()
  expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
  expect(dispatch.mock.calls.filter(c => c[3].type === 'archive')).toHaveLength(2)
})
