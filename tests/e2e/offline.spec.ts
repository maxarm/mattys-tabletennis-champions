import { readdir } from 'node:fs/promises'
import { test, expect } from '@playwright/test'
test('fresh cache supports offline restart, tournament and archive with local portraits and flags', async ({ page, context, request }) => {
  await request.get('/__version?v=a')
  await page.goto('/')
  await expect(page.getByText('Offline bereit auf diesem Gerät.')).toBeVisible()
  await context.setOffline(true)
  await page.close()
  const offline = await context.newPage()
  await offline.goto('/')
  await expect(offline.getByText('Offline bereit auf diesem Gerät.')).toBeVisible()
  const flags = (await readdir('public/flags')).filter(file => file.endsWith('.svg'))
  expect(flags).toHaveLength(23)
  expect(await offline.evaluate(async paths => (await Promise.all(paths.map(path => fetch('/flags/' + path).then(response => response.ok)))).every(Boolean), flags)).toBe(true)
  const manifest = await offline.evaluate(async () => (await fetch('/manifest.webmanifest')).json())
  expect(manifest.display).toBe('standalone')
  expect(manifest.icons).toHaveLength(3)
  expect(await offline.evaluate(async () => (await fetch('/icons/apple-touch-icon.png')).ok)).toBe(true)
  expect(await offline.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await offline.getByRole('radio', { name: 'Finale', exact: true }).check()
  await offline.getByRole('button', { name: /Teams auslosen/ }).click()
  await offline.getByRole('button', { name: 'Spiel 1 öffnen' }).click()
  const inputs = offline.locator('input[inputmode="numeric"]')
  await inputs.nth(0).fill('11'); await inputs.nth(1).fill('4')
  await expect(offline.locator('img').first()).toBeVisible()
  expect(await offline.locator('img').evaluateAll(images => images.every(image => image instanceof HTMLImageElement && image.complete && image.naturalWidth > 0))).toBe(true)
  await expect(offline.locator('svg').first()).toBeVisible()
  expect(await offline.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await offline.screenshot({ path: '.superpowers/sdd/2026-11-07-mattys-table-tennis/task-6-offline-match-390.png', fullPage: true })
  await offline.getByRole('button', { name: /Spiel abschließen/ }).click()
  await offline.getByRole('button', { name: /Zur Siegerehrung/ }).click()
  await offline.getByRole('button', { name: 'Speichern und Beenden' }).click()
  await offline.getByRole('button', { name: 'Archiv', exact: true }).click()
  await offline.getByRole('button', { name: /ansehen|öffnen/i }).first().click()
  await expect(offline.getByText('Archiviert', { exact: false }).first()).toBeVisible()
})
test('does not claim readiness when a mandatory own-cache entry is missing, even if another cache has it', async ({ page, request }) => {
  await request.get('/__version?v=a')
  await page.goto('/')
  await expect(page.getByText('Offline bereit auf diesem Gerät.')).toBeVisible()
  await page.evaluate(async () => {
    const name = (await caches.keys()).find(name => name.includes('precache'))!
    const cache = await caches.open(name)
    const key = (await cache.keys()).find(request => request.url.includes('/flags/'))!
    await (await caches.open('unrelated-cache')).put(key, (await cache.match(key))!)
    await cache.delete(key)
    navigator.serviceWorker.controller!.postMessage({ type: 'CHECK_OFFLINE' })
  })
  await expect(page.getByText(/Offline-Dateien konnten nicht vollständig bestätigt/)).toBeVisible()
  await expect(page.getByText('Offline bereit auf diesem Gerät.')).toHaveCount(0)
})
